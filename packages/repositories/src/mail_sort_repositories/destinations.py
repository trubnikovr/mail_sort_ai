from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class DestinationRecord:
    id: str
    name: str
    instruction: str
    mailbox: str
    enabled: bool = True
    use_for_ai: bool = True

    def __post_init__(self) -> None:
        normalized = "/".join(part.strip() for part in self.mailbox.split("/") if part.strip())
        object.__setattr__(self, "mailbox", normalized)


