class DestinationRepository:
    """Read the manually maintained catalog for the configured mailbox account."""

    def __init__(self, account_id: str, destinations: tuple[DestinationRecord, ...] = DESTINATIONS) -> None:
        self._account_id = account_id
        self._destinations = destinations

    def active_for_account(self, account_id: str) -> tuple[DestinationRecord, ...]:
        if account_id != self._account_id:
            return ()
        return tuple(destination for destination in self._destinations if destination.enabled)

    def for_ai(self, account_id: str) -> tuple[DestinationRecord, ...]:
        return tuple(
            destination
            for destination in self.active_for_account(account_id)
            if destination.use_for_ai
        )

    def get_active(self, account_id: str, destination_id: str) -> DestinationRecord:
        for destination in self.active_for_account(account_id):
            if destination.id == destination_id:
                return destination
        raise LookupError(f"Active destination {destination_id!r} was not found")
